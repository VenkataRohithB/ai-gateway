-- MCP tool servers behind the gateway (e.g. ToolHive proxies), which mandates may use them, and the key the
-- gateway signs short-lived tool passes with. Agents never reach a tool server directly.
CREATE TABLE tool_servers (
  id         text PRIMARY KEY CHECK (id ~ '^[a-z0-9-]{1,64}$'),
  name       text NOT NULL,
  url        text NOT NULL,                     -- the server's MCP endpoint, e.g. http://host.docker.internal:18111/mcp
  audience   text NOT NULL,                     -- aud of the passes for this server (ToolHive --oidc-audience)
  status     text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'suspended')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE mandate_tool_servers (
  mandate_id text NOT NULL REFERENCES mandates(id),
  server_id  text NOT NULL REFERENCES tool_servers(id),
  tools      text[] NOT NULL DEFAULT '{}',      -- allowed tool names; empty = every tool on the server
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (mandate_id, server_id)
);

-- One RSA key; generated by the gateway on first start. Only its public half leaves the gateway (JWKS).
CREATE TABLE signing_keys (
  kid         text PRIMARY KEY,
  private_pem text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now()
);

-- Tool calls share the usage table: model columns stay empty, these are set.
ALTER TABLE usage ADD COLUMN tool_server text, ADD COLUMN tool_name text;

GRANT SELECT, INSERT, UPDATE, DELETE ON tool_servers, mandate_tool_servers TO gateway_app;
GRANT SELECT, INSERT ON signing_keys TO gateway_app;
